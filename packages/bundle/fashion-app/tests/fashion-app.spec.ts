/** Fashion-app patch contract. */
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

describe('fashion-app patch', () => {
  it('disables generic sidebar and inserts project/research/analysis stack plus fashion shell', () => {
    const patch = readFileSync(join(root, 'cordis.patch.yml'), 'utf8')
    expect(patch).toContain('id: ui-sidebar')
    expect(patch).toContain('disabled: true')
    expect(patch).toContain('id: ui-settings-models')
    expect(patch).toContain('showWelcomeNotice: false')
    expect(patch).toContain('showDeepSeekOnboarding: false')
    expect(patch).toContain('id: fashion-project')
    expect(patch).toContain('@gentlexx/dsh-fashion-project')
    expect(patch).toContain('id: fashion-research')
    expect(patch).toContain('@gentlexx/dsh-fashion-research')
    expect(patch).toContain('id: fashion-analysis')
    expect(patch).toContain('@gentlexx/dsh-fashion-analysis')
    expect(patch).toContain('id: fashion-project-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-project-controller')
    expect(patch).toContain('id: fashion-research-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-research-controller')
    expect(patch).toContain('id: fashion-analysis-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-analysis-controller')
    expect(patch).toContain('id: fashion-feedback')
    expect(patch).toContain('@gentlexx/dsh-fashion-feedback')
    expect(patch).toContain('id: fashion-feedback-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-feedback-controller')
    expect(patch).toContain('id: fashion-evaluation')
    expect(patch).toContain('@gentlexx/dsh-fashion-evaluation')
    expect(patch).toContain('id: fashion-evaluation-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-evaluation-controller')
    expect(patch).toContain('id: fashion-agent')
    expect(patch).toContain('@gentlexx/dsh-fashion-agent')
    expect(patch).toContain('id: fashion-agent-controller')
    expect(patch).toContain('@gentlexx/dsh-api-fashion-agent-controller')
    expect(patch).toContain('id: ui-fashion-shell')
    expect(patch).toContain('@gentlexx/dsh-client-ui-fashion-shell')
    const projectAt = patch.indexOf('id: fashion-project')
    const researchAt = patch.indexOf('id: fashion-research')
    const analysisAt = patch.indexOf('id: fashion-analysis')
    const projectControllerAt = patch.indexOf('id: fashion-project-controller')
    const researchControllerAt = patch.indexOf('id: fashion-research-controller')
    const analysisControllerAt = patch.indexOf('id: fashion-analysis-controller')
    expect(projectAt).toBeGreaterThan(-1)
    expect(researchAt).toBeGreaterThan(projectAt)
    expect(analysisAt).toBeGreaterThan(researchAt)
    expect(projectControllerAt).toBeGreaterThan(analysisAt)
    expect(researchControllerAt).toBeGreaterThan(projectControllerAt)
    expect(analysisControllerAt).toBeGreaterThan(researchControllerAt)
  })

  it('does not load Fashion Agent context into the generic web-app patch', () => {
    const webPatch = readFileSync(join(root, '../web-app/cordis.patch.yml'), 'utf8')
    expect(webPatch).not.toContain('fashion-agent')
    expect(webPatch).not.toContain('@gentlexx/dsh-fashion-agent')
    expect(webPatch).not.toContain('@gentlexx/dsh-api-fashion-agent-controller')
    expect(webPatch).not.toContain('ui-fashion-shell')
  })
})
